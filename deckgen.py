"""
JML AI Analyst — v1 deck renderer.

build_deck(data: dict) -> bytes  (a .pptx file)

Builds exactly six native slides (no think-cell, no external template):
  1. Title      2. Agenda      3. Context
  4. Market Research (a real table)   5. Next Steps   6. Conclusion

Every section is optional in the payload; missing fields fall back to a
placeholder so a run never crashes on a thin brief. See CONTRACT.md for the
request shape.
"""

from io import BytesIO
from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN, MSO_ANCHOR
from pptx.enum.shapes import MSO_SHAPE

# ---- palette / type ----------------------------------------------------------
NAVY = RGBColor(0x1F, 0x2A, 0x44)
NAVY_SOFT = RGBColor(0x2E, 0x3D, 0x63)
GOLD = RGBColor(0xC8, 0xA4, 0x5C)
INK = RGBColor(0x22, 0x26, 0x2E)
GREY = RGBColor(0x6B, 0x72, 0x80)
LIGHT = RGBColor(0xF2, 0xF3, 0xF6)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)
FONT = "Calibri"

EMU_W = Inches(13.333)
EMU_H = Inches(7.5)


def _txt(slide, left, top, width, height, text, *, size=18, bold=False,
         color=INK, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, font=FONT,
         line_spacing=1.0, wrap=True):
    box = slide.shapes.add_textbox(left, top, width, height)
    tf = box.text_frame
    tf.word_wrap = wrap
    tf.vertical_anchor = anchor
    tf.margin_left = tf.margin_right = Pt(0)
    tf.margin_top = tf.margin_bottom = Pt(0)
    lines = text if isinstance(text, (list, tuple)) else [text]
    for i, line in enumerate(lines):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        p.line_spacing = line_spacing
        bullet = isinstance(line, dict)
        s = line.get("text", "") if bullet else str(line)
        run = p.add_run()
        run.text = ("•  " + s) if bullet else s
        run.font.size = Pt(line.get("size", size) if bullet else size)
        run.font.bold = line.get("bold", bold) if bullet else bold
        run.font.name = font
        run.font.color.rgb = line.get("color", color) if bullet else color
        if bullet and i > 0:
            p.space_before = Pt(6)
    return box


def _rect(slide, left, top, width, height, fill, line=None):
    sp = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, left, top, width, height)
    sp.fill.solid()
    sp.fill.fore_color.rgb = fill
    if line is None:
        sp.line.fill.background()
    else:
        sp.line.color.rgb = line
        sp.line.width = Pt(0.75)
    sp.shadow.inherit = False
    return sp


def _blank(prs):
    return prs.slides.add_slide(prs.slide_layouts[6])


def _footer(slide, meta, page):
    _rect(slide, 0, EMU_H - Inches(0.34), EMU_W, Inches(0.34), LIGHT)
    _txt(slide, Inches(0.55), EMU_H - Inches(0.33), Inches(9.0), Inches(0.3),
         meta.get("footer", "JML Operations — draft generated by the AI Analyst"),
         size=9, color=GREY, anchor=MSO_ANCHOR.MIDDLE)
    _txt(slide, EMU_W - Inches(1.4), EMU_H - Inches(0.33), Inches(0.85), Inches(0.3),
         str(page), size=9, color=GREY, align=PP_ALIGN.RIGHT, anchor=MSO_ANCHOR.MIDDLE)


def _content_header(slide, title, kicker=None):
    _rect(slide, 0, 0, Inches(0.22), EMU_H, GOLD)  # left spine
    if kicker:
        _txt(slide, Inches(0.6), Inches(0.5), Inches(11.5), Inches(0.4),
             kicker.upper(), size=12, bold=True, color=GOLD)
    _txt(slide, Inches(0.6), Inches(0.92), Inches(12.1), Inches(1.2),
         title, size=26, bold=True, color=NAVY, line_spacing=1.05)
    _rect(slide, Inches(0.62), Inches(2.02), Inches(2.2), Pt(2.5), NAVY)


def _s(data, key, default=None):
    v = data.get(key)
    return v if isinstance(v, dict) else (default or {})


# ---- slides ------------------------------------------------------------------
def slide_cover(prs, data, meta):
    s = _blank(prs)
    _rect(s, 0, 0, EMU_W, EMU_H, NAVY)
    _rect(s, 0, Inches(4.55), EMU_W, Pt(3), GOLD)
    c = _s(data, "cover")
    _txt(s, Inches(0.9), Inches(0.9), Inches(8), Inches(0.4),
         meta.get("kicker", "CONSULTING PROPOSAL"), size=13, bold=True, color=GOLD)
    _txt(s, Inches(0.9), Inches(2.3), Inches(11.5), Inches(2.1),
         c.get("title") or "Draft proposal", size=40, bold=True, color=WHITE, line_spacing=1.05)
    _txt(s, Inches(0.9), Inches(4.8), Inches(11.5), Inches(1.4),
         c.get("subtitle") or meta.get("subject", ""), size=18, color=RGBColor(0xC7, 0xCD, 0xDA),
         line_spacing=1.2)
    _txt(s, Inches(0.9), EMU_H - Inches(0.95), Inches(11.5), Inches(0.5),
         meta.get("date", ""), size=12, color=RGBColor(0x9A, 0xA3, 0xB5))
    return s


def slide_agenda(prs, data, meta):
    s = _blank(prs)
    a = _s(data, "agenda")
    _content_header(s, a.get("title") or "Topics for today's discussion", "Agenda")
    items = a.get("items") or ["Context", "Market Research", "Next Steps"]
    top = Inches(2.55)
    for i, it in enumerate(items):
        y = top + Inches(1.15) * i
        chip = _rect(s, Inches(0.7), y, Inches(0.62), Inches(0.62), NAVY)
        _txt(s, Inches(0.7), y, Inches(0.62), Inches(0.62), str(i + 1),
             size=22, bold=True, color=WHITE, align=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE)
        _txt(s, Inches(1.6), y, Inches(10.5), Inches(0.62), str(it),
             size=20, bold=True, color=NAVY, anchor=MSO_ANCHOR.MIDDLE)
    _footer(s, meta, 2)
    return s


def _bullets(slide, bullets, top=Inches(2.35), left=Inches(0.7), width=Inches(12.0),
             size=16, gap=1.18):
    y = top
    for b in bullets:
        txt = b.get("text", "") if isinstance(b, dict) else str(b)
        sub = b.get("sub") if isinstance(b, dict) else None
        _rect(slide, left, y + Inches(0.09), Inches(0.12), Inches(0.12), GOLD)
        box = _txt(slide, left + Inches(0.33), y, width, Inches(1.0), txt,
                   size=size, color=INK, line_spacing=1.1)
        # rough vertical advance: ~1 line per ~90 chars
        lines = max(1, (len(txt) // 92) + 1)
        y = y + Inches(0.42 * lines + 0.2)
        if sub:
            _txt(slide, left + Inches(0.33), y - Inches(0.12), width, Inches(0.6),
                 sub, size=12, color=GREY)
            y = y + Inches(0.4)
    return y


def slide_context(prs, data, meta):
    s = _blank(prs)
    c = _s(data, "context")
    _content_header(s, c.get("title") or "Context", "Context")
    bullets = c.get("bullets") or ["[No context captured from the brief.]"]
    _bullets(s, bullets, size=16)
    _footer(s, meta, 3)
    return s


def slide_market(prs, data, meta):
    s = _blank(prs)
    m = _s(data, "market_research")
    _content_header(s, m.get("title") or "Market research", "Market Research")
    rows = m.get("rows") or []
    left, top, width = Inches(0.62), Inches(2.3), Inches(12.1)
    if not rows:
        _txt(s, left, top, width, Inches(1.0),
             "No market findings met the sourcing bar for this brief.",
             size=15, color=GREY)
    else:
        headers = ["Who", "What is happening", "Why it matters"]
        n = len(rows) + 1
        height = Inches(min(4.2, 0.5 + 0.9 * len(rows)))
        tbl = s.shapes.add_table(n, 3, left, top, width, height).table
        tbl.columns[0].width = Inches(2.7)
        tbl.columns[1].width = Inches(5.4)
        tbl.columns[2].width = Inches(4.0)
        for j, h in enumerate(headers):
            cell = tbl.cell(0, j)
            cell.fill.solid(); cell.fill.fore_color.rgb = NAVY
            cell.vertical_anchor = MSO_ANCHOR.MIDDLE
            p = cell.text_frame.paragraphs[0]; r = p.add_run(); r.text = h
            r.font.size = Pt(12); r.font.bold = True; r.font.color.rgb = WHITE; r.font.name = FONT
        for i, row in enumerate(rows, start=1):
            vals = [row.get("actor", ""), row.get("finding", ""), row.get("implication", "")]
            for j, val in enumerate(vals):
                cell = tbl.cell(i, j)
                cell.fill.solid(); cell.fill.fore_color.rgb = WHITE if i % 2 else LIGHT
                cell.vertical_anchor = MSO_ANCHOR.MIDDLE
                cell.margin_top = cell.margin_bottom = Pt(3)
                p = cell.text_frame.paragraphs[0]; p.line_spacing = 1.0
                r = p.add_run(); r.text = str(val)
                r.font.size = Pt(11); r.font.name = FONT
                r.font.color.rgb = NAVY if j == 0 else INK
                r.font.bold = (j == 0)
    srcs = m.get("sources") or []
    if srcs:
        _txt(s, left, EMU_H - Inches(0.75), width, Inches(0.4),
             "Sources: " + "  ".join(f"[{i+1}] {u}" for i, u in enumerate(srcs)),
             size=8, color=GREY)
    _footer(s, meta, 4)
    return s


def slide_next_steps(prs, data, meta):
    s = _blank(prs)
    n = _s(data, "next_steps")
    _content_header(s, n.get("title") or "Next steps", "Next Steps")
    bullets = n.get("bullets") or [
        "Confirm scope, timeline and stakeholders with the client.",
        "Develop the detailed phase plan and deliverables.",
        "Align on commercial terms and project team.",
    ]
    _bullets(s, bullets, size=16)
    _footer(s, meta, 5)
    return s


def slide_closing(prs, data, meta):
    s = _blank(prs)
    _rect(s, 0, 0, EMU_W, EMU_H, NAVY)
    _rect(s, Inches(0.9), Inches(3.05), Inches(2.2), Pt(3), GOLD)
    c = _s(data, "closing")
    _txt(s, Inches(0.9), Inches(3.25), Inches(11.5), Inches(1.4),
         c.get("title") or "Thank you", size=34, bold=True, color=WHITE)
    _txt(s, Inches(0.9), Inches(4.6), Inches(11.5), Inches(1.2),
         c.get("subtitle") or "This is a draft generated by the JML AI Analyst for discussion.",
         size=16, color=RGBColor(0xC7, 0xCD, 0xDA), line_spacing=1.2)
    return s


def build_deck(data: dict) -> bytes:
    data = data or {}
    meta = _s(data, "meta")
    prs = Presentation()
    prs.slide_width = EMU_W
    prs.slide_height = EMU_H
    slide_cover(prs, data, meta)
    slide_agenda(prs, data, meta)
    slide_context(prs, data, meta)
    slide_market(prs, data, meta)
    slide_next_steps(prs, data, meta)
    slide_closing(prs, data, meta)
    buf = BytesIO()
    prs.save(buf)
    return buf.getvalue()
