"""Build the n8n code for the four-agent Phase Architect chain (v3) from the repo sources.

Writes:
  n8n/code/chain_check.js    "Chain check" Code node = validate_plan_v2.js + deliverable_formats.json + v3/chain.js
                             (each wrapped so their top-level names cannot clash) + the n8n wrapper below them
                             (n8n/code/_chain_check_tail.js)
  n8n/code/architect_input.js  "Architect input": METHOD_LIBRARY and SIZING_COMMON from method_library.json
  n8n/prompts/10_chain/*       the four system messages and schemas as pasted into the agent and parser nodes
Edit the sources, run `python3 phase_architect/build_n8n_chain.py`, test (`node n8n/tests/chain_test.js`), then paste.
"""
import json, os, re, shutil

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PA = os.path.join(R, "phase_architect")
rd = lambda *p: open(os.path.join(*p), encoding="utf-8").read()

IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
def js(v):
    """A JS literal with single-quoted strings and bare keys: far fewer escapes when pasted into n8n through JSON."""
    if isinstance(v, dict):
        return "{" + ", ".join((k if IDENT.match(k) else js(k)) + ": " + js(x) for k, x in v.items()) + "}"
    if isinstance(v, list):
        return "[" + ", ".join(js(x) for x in v) + "]"
    if isinstance(v, str):
        if "'" in v and '"' not in v:
            return json.dumps(v, ensure_ascii=False)
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'"
    return json.dumps(v)

# ---- Chain check ----
val = rd(PA, "validate_plan_v2.js")
exp = "if (typeof module !== 'undefined') module.exports = { validatePlan, weeksAvailable, parseDeadline, LIM };"
assert val.count(exp) == 1
val = val.replace(exp, "return { validatePlan };")

chain = rd(PA, "v3", "chain.js")
req1 = "const { validatePlan } = require('../validate_plan_v2.js');"
req2 = "const FORMATS = require('../deliverable_formats.json');"
assert chain.count(req1) == 1 and chain.count(req2) == 1
formats = json.loads(rd(PA, "deliverable_formats.json"))
formats.pop("_note", None)
chain = chain.replace(req1, "// validatePlan: from the validator block above").replace(
    req2, "const FORMATS = " + js(formats) + ";")
m = re.search(r"if \(typeof module !== 'undefined'\) module\.exports = (\{[^}]*\});", chain)
assert m, "chain.js export line not found"
chain = chain.replace(m.group(0), "return " + m.group(1) + ";")

tail = rd(R, "n8n", "code", "_chain_check_tail.js")
head = ("// Chain check (Code, run once for each item). GENERATED by `python3 phase_architect/build_n8n_chain.py` from\n"
        "// phase_architect/validate_plan_v2.js, phase_architect/deliverable_formats.json, phase_architect/v3/chain.js and\n"
        "// n8n/code/_chain_check_tail.js. Edit those files, rebuild, test, then paste here.\n")
out = (head
       + "const { validatePlan } = (() => {\n" + val + "\n})();\n"
       + "const C = (() => {\n" + chain + "\n})();\n"
       + tail)
open(os.path.join(R, "n8n", "code", "chain_check.js"), "w", encoding="utf-8").write(out)
print("built n8n/code/chain_check.js", len(out), "chars")

# ---- Architect input ----
lib = json.loads(rd(PA, "method_library.json"))
ai_path = os.path.join(R, "n8n", "code", "architect_input.js")
ai = rd(ai_path)
ml_line = "const METHOD_LIBRARY = " + js(lib["archetypes"]) + ";"
ai = re.sub(r"^const METHOD_LIBRARY = .*;$", lambda _: ml_line, ai, count=1, flags=re.M)
sc_line = "const SIZING_COMMON = " + js(lib["sizing_common"]) + ";"
if re.search(r"^const SIZING_COMMON = .*;$", ai, flags=re.M):
    ai = re.sub(r"^const SIZING_COMMON = .*;$", lambda _: sc_line, ai, count=1, flags=re.M)
else:
    ai = re.sub(r"^(const METHOD_LIBRARY = .*;)$", lambda mm: mm.group(1) + "\n" + sc_line, ai, count=1, flags=re.M)
if "sizing_common: SIZING_COMMON" not in ai:
    ai = ai.replace("  method_library: METHOD_LIBRARY\n};", "  method_library: METHOD_LIBRARY,\n  sizing_common: SIZING_COMMON\n};")
assert "sizing_common: SIZING_COMMON" in ai
open(ai_path, "w", encoding="utf-8").write(ai)
print("built n8n/code/architect_input.js", len(ai), "chars")

# ---- prompts and schemas, as pasted ----
dst = os.path.join(R, "n8n", "prompts", "10_chain")
os.makedirs(dst, exist_ok=True)
for stage, (p, s) in {"lead": ("prompt_lead.md", "schema_lead.json"), "workstreams": ("prompt_workstreams.md", "schema_workstreams.json"),
                      "deliverables": ("prompt_deliverables.md", "schema_deliverables.json"),
                      "governance": ("prompt_governance.md", "schema_governance.json")}.items():
    shutil.copyfile(os.path.join(PA, "v3", p), os.path.join(dst, f"{stage}_system.md"))
    # the parser node takes the schema as one compact string
    open(os.path.join(dst, f"{stage}_schema.json"), "w", encoding="utf-8").write(json.dumps(json.loads(rd(PA, "v3", s)), ensure_ascii=False))
print("copied prompts and schemas to n8n/prompts/10_chain")
